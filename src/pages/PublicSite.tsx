import { useEffect, useState } from "react";
import { useParams, Link } from "react-router-dom";
import { supabase } from "@/integrations/supabase/client";
import PublicSiteRenderer, { SiteDoc } from "@/components/byow/PublicSiteRenderer";
import SeoHead from "@/components/SeoHead";
import { Loader2, Rocket } from "lucide-react";

export default function PublicSite() {
  const { ref } = useParams<{ ref: string }>();
  const [doc, setDoc] = useState<SiteDoc | null>(null);
  const [displayName, setDisplayName] = useState("");
  const [status, setStatus] = useState<"draft" | "published">("draft");
  const [loading, setLoading] = useState(true);
  const [notFound, setNotFound] = useState(false);

  useEffect(() => {
    if (!ref) return;
    let alive = true;
    (async () => {
      const { data, error } = await supabase
        .from("byow_generated_sites")
        .select("doc, display_name, status")
        .eq("ref", ref)
        .maybeSingle();
      if (!alive) return;
      if (error || !data) {
        setNotFound(true);
      } else {
        setDoc(data.doc as SiteDoc);
        setDisplayName(data.display_name);
        setStatus(data.status as any);
      }
      setLoading(false);
    })();
    return () => { alive = false; };
  }, [ref]);

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-black text-white">
        <Loader2 className="h-6 w-6 animate-spin" />
      </div>
    );
  }
  if (notFound || !doc) {
    return (
      <div className="min-h-screen flex flex-col items-center justify-center bg-black text-white gap-4">
        <h1 className="text-2xl font-light">Site not found</h1>
        <Link to="/byow" className="text-sm underline">Create your own</Link>
      </div>
    );
  }

  return (
    <>
      <SeoHead
        title={`${displayName} — built with Pixcellor`}
        description={`${displayName} — generated by Pixcellor BYOW.`}
        path={`/s/${ref}`}
      />
      {status === "draft" && (
        <div className="sticky top-0 z-50 bg-black text-white px-4 py-2 text-xs flex items-center justify-center gap-3 border-b border-white/10">
          <Rocket className="h-3.5 w-3.5" />
          <span>Preview · publish to claim your domain and unlock edits.</span>
          <Link to="/byow#pricing" className="underline font-semibold">Publish →</Link>
        </div>
      )}
      <PublicSiteRenderer doc={doc} />
    </>
  );
}
